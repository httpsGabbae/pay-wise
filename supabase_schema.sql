CREATE TABLE IF NOT EXISTS public.employee_loans (
    loan_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id INTEGER NOT NULL REFERENCES public.employees (employee_id) ON DELETE CASCADE,
    loan_type_id INTEGER NOT NULL REFERENCES public.loan_types (loan_type_id) ON UPDATE CASCADE,
