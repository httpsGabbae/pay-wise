CREATE TABLE IF NOT EXISTS public.attendance (
    attendance_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id INTEGER NOT NULL REFERENCES public.employees (employee_id) ON DELETE CASCADE,
    period_id INTEGER REFERENCES public.payroll_periods (period_id) ON DELETE SET NULL,
    attendance_date DATE NOT NULL,
    time_in TIME,
    time_out TIME,
    daily_rate NUMERIC(10,2) NOT NULL DEFAULT 0.00,
    absences_count NUMERIC(5,2) NOT NULL DEFAULT 0.00,
    tardiness_hours NUMERIC(5,2) NOT NULL DEFAULT 0.00,
    undertime_hours NUMERIC(5,2) NOT NULL DEFAULT 0.00,
    overtime_hours NUMERIC(5,2) NOT NULL DEFAULT 0.00,
    computed_deduction NUMERIC(10,2) NOT NULL DEFAULT 0.00,
    computed_overtime NUMERIC(10,2) NOT NULL DEFAULT 0.00,
    status VARCHAR(10) NOT NULL DEFAULT 'Present'
        CHECK (status IN ('Present', 'Late', 'Absent', 'On Leave', 'Half Day')),
    remarks VARCHAR(255),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_emp_attendance_date UNIQUE (employee_id, attendance_date)
);

